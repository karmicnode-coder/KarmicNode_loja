// Calcula o preço unitário de uma linha a partir do design (nunca confia no navegador)
export function unitPrice(item) {
  const p = CATALOG[item.id];
  if (!p) return null;
  let cents = p.price_cents;
  const d = item.design;
  if (p.custom && d && d.views) {
    const tech = TECH[d.tech] || TECH.emb;
    const front = Array.isArray(d.views.front) ? d.views.front.length : 0;
    const back = p.back && Array.isArray(d.views.back) ? d.views.back.length : 0;
    const all = [].concat(d.views.front || [], p.back ? (d.views.back || []) : []);
    if (front) cents += tech.front + Math.max(0, front - 1) * EXTRA_LAYER;
    if (back) cents += tech.back + Math.max(0, back - 1) * EXTRA_LAYER;
    if (all.some((l) => l && l.type === 'image')) cents += IMAGE_FEE;
  }
  return cents;
}

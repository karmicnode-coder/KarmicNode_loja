export type TKey = keyof typeof translations['pt']

export function createT(lang: Lang) {
  return (key: TKey): string => {
    const val = translations[lang][key] ?? translations['pt'][key]
    return Array.isArray(val) ? (val as string[]).join(', ') : String(val)
  }
}

export function getArr(lang: Lang, key: TKey): string[] {
  const val = translations[lang][key]
  return Array.isArray(val) ? (val as string[]) : []
}
